// Reuse the established reading-badge artwork for each chronological reading.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const plan = JSON.parse(await readFile(path.join(root, 'chronbible/data/readings.json'), 'utf8'));
const rows = (await readFile(path.join(root, 'scripts/chronological-badge-themes.txt'), 'utf8')).trim().split('\n').map(row => row.split('|'));
if (rows.length !== plan.readings.length) throw new Error('Every chronological reading needs a badge');
const designs = new Set();
const catalog = plan.readings.map((reading, i) => {
  const [number, motif] = rows[i];
  if (Number(number) !== reading.number) throw new Error(`Reading order mismatch: ${reading.id}`);
  const style = Math.floor(i / 12) % 6;
  const detail = i % 4;
  let palette = (i * 7) % 12;
  let attempts = 0;
  while (designs.has(`${motif}:${palette}:${style}:${detail}`)) {
    if (++attempts >= 12) throw new Error(`Choose another motif for ${reading.id}`);
    palette = (palette + 1) % 12;
  }
  designs.add(`${motif}:${palette}:${style}:${detail}`);
  return { id: reading.id, day: reading.number, book: reading.section, label: `${motif} · Reading ${reading.number}`, title: reading.title, reference: reading.reference, motif, palette, style, detail };
});
const runtime = await readFile(path.join(root, 'scripts/reading-badge-art.cjs'), 'utf8');
const output = `/* Generated by scripts/build-chronological-badges.mjs. */\n${runtime.replace('/* CATALOG */ []', JSON.stringify(catalog))}`;
await writeFile(path.join(root, 'chronbible/reading-badges.js'), output);
if (process.argv[2]) {
  const app = path.resolve(process.argv[2]);
  const appPlan = JSON.parse(await readFile(path.join(app, 'data/chronologicalBiblePlan.json'), 'utf8'));
  if (JSON.stringify(appPlan.readings) !== JSON.stringify(plan.readings)) throw new Error('Website and app reading plans differ');
  await writeFile(path.join(app, 'lib/readingBadges.js'), output);
}
console.log(`Generated ${catalog.length} chronological reading badges.`);
